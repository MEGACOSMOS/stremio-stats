// A primeira língua conhecida de uma lista ("en-US", "fr", …); senão português.
export function linguaDe(...candidatos) {
  for (const c of candidatos.flat()) {
    const l = String(c || '').trim().toLowerCase().slice(0, 2);
    if (l in LINGUAS) return l;
  }
  return 'pt';
}

