const cache = new Map();

// Tudo o que é preciso para escrever numa língua: as frases e as ferramentas
// para números, datas, géneros e países.
export function textos(lingua) {
  const l = lingua in T ? lingua : 'pt';
  if (cache.has(l)) return cache.get(l);
  const i = ORDEM.indexOf(l);
  const local = LOCAIS[l];
  let nomesPaises = null;
  try { nomesPaises = new Intl.DisplayNames([local], { type: 'region' }); } catch { /* fica o nome em inglês */ }
  const numero = (n) => Math.round(n).toLocaleString(local);
  const t = {
    ...T[l],
    lingua: l,
    local,
    meses: MESES[l],
    mesesCurtos: MESES_CURTOS[l],
    dias: DIAS[l],
    diasCurtos: DIAS_CURTOS[l],
    noDia: (d) => NO_DIA[l][d],
    numero,
    decimal: (n) => n.toLocaleString(local, { minimumFractionDigits: 1, maximumFractionDigits: 1 }),
    filmes: (n) => T[l].filmes(n, numero(n)),
    mesAno: (chave, curto = false) => {
      const [a, m] = String(chave).split('-').map(Number);
      return `${(curto ? MESES_CURTOS : MESES)[l][m - 1]} ${a}`;
    },
    dataLonga: (ms, fuso) => {
      const opcoes = { day: 'numeric', month: 'long', year: 'numeric' };
      try { return new Date(ms).toLocaleDateString(local, { ...opcoes, timeZone: fuso }); } catch { return new Date(ms).toLocaleDateString(local, opcoes); }
    },
    genero: (g) => GENEROS[g]?.[i] || g,
    pais: (p) => {
      if (PAISES_ANTIGOS[p]) return PAISES_ANTIGOS[p][i];
      const codigo = PAISES[p];
      if (!codigo || !nomesPaises) return p;
      try { return nomesPaises.of(codigo) || p; } catch { return p; }
    },
    periodo: (hora) => {
      if (hora >= 5 && hora < 12) return PERIODOS[l][0];
      if (hora >= 12 && hora < 19) return PERIODOS[l][1];
      if (hora >= 19) return PERIODOS[l][2];
      return PERIODOS[l][3];
    },
    periodos: PERIODOS[l],
    hora: (h) => ({ pt: `${h}h`, en: `${h}:00`, fr: `${h} h`, es: `${h} h`, it: `${h}:00` })[l],
  };
  cache.set(l, t);
  return t;
}
